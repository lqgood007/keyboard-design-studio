/* ========== 步进控件（− 数值 ＋） ========== */
const STEP_MAP = { x: 0.25, y: 0.25, w: 0.25, h: 0.25, r: 5 };
function bindSteppers() {
  document.querySelectorAll('.step-btn').forEach((btn) => {
    const field = btn.dataset.field;
    const dir = btn.classList.contains('step-minus') ? -1 : 1;
    const step = STEP_MAP[field] || 0.25;
    let timer = null;
    const apply = () => {
      if (state.selected < 0) return;
      const el = $(`p-${field}`);
      let v = parseFloat(el.value);
      if (isNaN(v)) v = state.keys[state.selected][field] || 0;
      let nv = round(v + dir * step);
      if (field === 'w' || field === 'h') nv = Math.max(0.25, nv);
      updateKey({ [field]: nv });
    };
    btn.addEventListener('click', apply);
    // 按住连续步进（120ms 间隔）
    btn.addEventListener('mousedown', () => {
      timer = setInterval(apply, 120);
    });
    ['mouseup', 'mouseleave'].forEach((ev) => {
      btn.addEventListener(ev, () => clearInterval(timer));
    });
  });
}

