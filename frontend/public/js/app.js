/* ========== KLE raw 数组 → 键列表 ==========
 * 与 kle-serial 解析语义一致：
 *   - 字符串元素：1u 键，标签=字符串，继承前一个对象的属性
 *   - 对象元素：属性声明（应用于其后字符串键）；连续对象时前一个成为无标签键
 *   - x：行内累计（对象 x 为相对前一键的额外偏移，行首为相对行起点）
 *   - y：行首对象 y 为行偏移；行结束 y += 行最大高度
 */
function flattenRows(rows) {
  const keys = [];
  let y = 0;
  // KLE 语义：
  //  - r/rx/ry 为跨行持久状态（Atreus/Ergodox 旋转簇依赖继承）
  //  - 设置 rx/ry 时 x/y 重置到旋转中心（kle-serial 同款）
  //  - 对象只更新状态不产生键；字符串才产生键（空串 = 空键）
  let rot = { r: 0, rx: 0, ry: 0 };
  for (let ri = 0; ri < rows.length; ri++) {
    const row = Array.isArray(rows[ri]) ? rows[ri] : [];
    // KLE：行开始 x = 上一行 rotation_x（旋转簇后行从旋转中心续排）
    let x = rot.rx;
    let rowMaxH = 1;
    let pending = null;

    const emit = (props, label, ci) => {
      const w = props.w || 1;
      const h = props.h || 1;
      const r = props.r != null ? props.r : rot.r;
      keys.push({
        ri, ci, x, y, w, h, r,
        rx: rot.rx,
        ry: rot.ry,
        label: label || '',
      });
      x += w;
      rowMaxH = Math.max(rowMaxH, h);
    };

    for (let ci = 0; ci < row.length; ci++) {
      const item = row[ci];
      if (item && typeof item === 'object') {
        // KLE 顺序：先 r/rx/ry（rx/ry 重置 x/y 到旋转中心），后 y/x 偏移
        if (item.r != null) rot.r = item.r;
        if (item.rx != null || item.ry != null) {
          if (item.rx != null) rot.rx = item.rx;
          if (item.ry != null) rot.ry = item.ry;
          x = rot.rx;
          y = rot.ry;
        }
        if (item.y) y += item.y;
        x += item.x || 0;
        pending = item;
      } else {
        emit(pending || {}, String(item), ci);
        pending = null;
      }
    }
    // KLE：行结束 x 重置到 rotation_x（旋转簇后行从旋转中心开始）
    x = rot.rx;
    y += rowMaxH;
  }
  return keys;
}
function serializeRows(keys) {
  // 按行分组（保持原始顺序）
  const rows = [];
  const byRow = {};
  for (const k of keys) {
    (byRow[k.ri] = byRow[k.ri] || []).push(k);
  }
  const riList = Object.keys(byRow).map(Number).sort((a, b) => a - b);
  let prevEndY = 0; // 上一行结束时 y（flattenRows: 行结束 y += rowMaxH）
  let prevRot = { r: 0, rx: 0, ry: 0 }; // 上一行结束时旋转状态（KLE：行结束 x 重置到 rotation_x）
  for (const ri of riList) {
    const rowKeys = byRow[ri];
    const rowArr = [];
    let prevX = 0;
    let prevY = 0;
    let first = true;
    let rowMaxH = 1;
    for (const k of rowKeys) {
      const attrs = {};
      const newCluster = k.r !== prevRot.r || k.rx !== prevRot.rx || k.ry !== prevRot.ry;
      // 行内 gap 相对前一键尾；行首 gap 相对"行开始位置"
      const gap = +(k.x - (first ? (newCluster ? k.rx : prevRot.rx) : prevX)).toFixed(4);
      if (first) {
        if (Math.abs(gap) > 0.001) attrs.x = round(gap);
        // 新旋转簇：y 相对旋转中心（ry）；常规行：y 相对上一行结束 y（默认行距 1）
        const base = newCluster ? k.ry : prevEndY;
        const dy = +(k.y - base).toFixed(4);
        if (Math.abs(dy - 1) > 0.001 && Math.abs(dy) > 0.001) attrs.y = round(dy);
        if (newCluster) {
          attrs.r = round(k.r);
          attrs.rx = round(k.rx);
          attrs.ry = round(k.ry);
          prevRot = { r: k.r, rx: k.rx, ry: k.ry };
        }
        prevY = k.y;
      } else {
        if (Math.abs(gap) > 0.001) attrs.x = round(gap);
        // 行内 y 偏移（Atreus 阶梯列等）
        const dy = +(k.y - prevY).toFixed(4);
        if (Math.abs(dy) > 0.001) attrs.y = round(dy);
        prevY = k.y;
      }
      if (Math.abs(k.w - 1) > 0.001) attrs.w = round(k.w);
      if (Math.abs(k.h - 1) > 0.001) attrs.h = round(k.h);
      if (Object.keys(attrs).length) rowArr.push(attrs);
      rowArr.push(k.label);
      prevX = k.x + k.w;
      rowMaxH = Math.max(rowMaxH, k.h);
      first = false;
    }
    rows.push(rowArr);
    // 行结束 y = 最后键 y + 行最大 h（与 flattenRows 的 y += rowMaxH 一致）
    prevEndY = rowKeys[rowKeys.length - 1].y + rowMaxH;
  }
  return rows;
}
function round(v) { return Math.round(v * 10000) / 10000; }

