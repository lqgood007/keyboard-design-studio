/* ========== 生成 ========== */
async function generate() {
  const btn = $('btn-generate');
  btn.disabled = true;
  setStatus('正在生成（定位板 / PCB / 外壳）…', '');
  try {
    const rows = state.rows;
    if (!rows.length) throw new Error('配列为空');
    const options = collectOptions();
    const res = await fetch('/api/generate', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ kle: rows, options }),
    });
    if (!res.ok) {
      const err = await res.json().catch(() => ({}));
      throw new Error(err.error || `HTTP ${res.status}`);
    }
    const blob = await res.blob();
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `keyboard_${Date.now()}.zip`;
    document.body.appendChild(a);
    a.click();
    a.remove();
    URL.revokeObjectURL(url);
    setStatus('✅ 生成成功，zip 已下载（plate.dxf / main.kicad_pcb / case.stl 等）', 'ok');
    showReport(rows.length, options);
  } catch (e) {
    setStatus('生成失败: ' + e.message, 'err');
  } finally {
    btn.disabled = false;
  }
}

function collectOptions() {
  return {
    cutout: +$('o-cutout').value || 14,
    expand: +$('o-expand').value || 5,
    bottomThickness: +$('o-bottom').value || 3,
    plateThickness: +$('o-plate').value || 1.5,
    controller: $('o-controller').checked,
    screwHoles: $('o-screw').checked,
    screwDia: +$('o-screw-dia').value || 3.2,
  };
}

/* 3D 预览：调用 /api/preview 生成，取 case.stl 渲染 */
async function preview3d() {
  setStatus('正在生成 3D 预览…', '');
  try {
    const rows = state.rows;
    if (!rows.length) throw new Error('配列为空');
    const res = await fetch('/api/preview', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ kle: rows, options: collectOptions() }),
    });
    if (!res.ok) throw new Error('预览生成失败');
    const data = await res.json();
    if (!data.ok) throw new Error(data.error || '预览生成失败');
    const stlRes = await fetch(`/api/jobs/${data.jobId}/files/case.stl`);
    if (!stlRes.ok) throw new Error('获取 STL 失败');
    const stlText = await stlRes.text();
    window.dispatchEvent(new CustomEvent('kb-preview-stl', { detail: { stl: stlText, keys: state.keys } }));
    setStatus(`3D 预览已生成（${data.report.keyCount} 键）`, 'ok');
  } catch (e) {
    setStatus('3D 预览失败: ' + e.message, 'err');
  }
}

